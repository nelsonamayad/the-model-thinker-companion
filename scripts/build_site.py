FAMILY = {f[0]: f for f in FAMILIES}
ENGINES = {
    "Agent-based": "../agent-based.qmd",
    "Equation-based": "../index.qmd#category=Equation-based",
}
USES = ["Reason", "Explain", "Design", "Communicate", "Act", "Predict", "Explore"]

CALLOUT_RE = re.compile(r'::: \{\.callout-note appearance="minimal" \.book-source\}\n.*?\n:::\n', re.S)
CODE_START = "<!-- Model code: generated by scripts/build_site.py from the cells above. Don't edit. -->"
CODE_END = "<!-- End of generated model code. -->"
CODE_RE = re.compile(re.escape(CODE_START) + r".*?" + re.escape(CODE_END) + r"\n?", re.S)


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(path, text):
    old = read(path) if os.path.exists(path) else None
    if old != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        return True
    return False


def split_list(s):
    items, cur, q = [], "", None
    for ch in s:
        if q:
            if ch == q:
                q = None
            else:
                cur += ch
        elif ch in "\"'":
            q = ch
        elif ch == ",":
            items.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        items.append(cur.strip())
    return items


def parse_front(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None, text, ""
    meta = {}
    for line in m.group(1).split("\n"):
        if not line.strip() or line.lstrip().startswith("#") or line.startswith(" "):
            continue
        k, _, v = line.partition(":")
        v = v.strip()
        if v.startswith("[") and v.endswith("]"):
            meta[k.strip()] = split_list(v[1:-1])
        else:
            if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
                v = v[1:-1].replace('\\"', '"')
            meta[k.strip()] = v
    return meta, text[m.end():], m.group(1)


def set_front_line(front, key, value):
    pat = re.compile(rf"^{re.escape(key)}:.*$", re.M)
    if pat.search(front):
        return pat.sub(lambda _: f"{key}: {value}", front)
    return front + f"\n{key}: {value}"


def load_entries():
    entries = []
    for path in sorted(glob.glob(os.path.join(ROOT, "models", "*.qmd"))):
        text = read(path)
        meta, body, front = parse_front(text)
        if meta is None:
            sys.exit(f"{path}: no front matter")
        slug = os.path.splitext(os.path.basename(path))[0]
        for key in ["title", "order", "family", "engine", "chapter", "pages", "tool", "reference", "verified"]:
            if key not in meta:
                sys.exit(f"{slug}: missing `{key}` in front matter")
        if meta["family"] not in FAMILY:
            sys.exit(f"{slug}: unknown family {meta['family']!r}")
        if meta["engine"] not in ENGINES:
            sys.exit(f"{slug}: engine must be one of {list(ENGINES)}")
        entries.append({"path": path, "slug": slug, "meta": meta, "body": body, "front": front})
    entries.sort(key=lambda e: int(e["meta"]["order"]))
    return entries


def callout(e):
    m = e["meta"]
    fam = FAMILY[m["family"]]
    lines = [
        '::: {.callout-note appearance="minimal" .book-source}',
        f'Model **#{m["order"]}** · *The Model Thinker*, chapter {m["chapter"]}, '
        f'"{m.get("chapter-title", "")}", pp. {m["pages"]}.',
        "",
        f'Filed under [{m["family"]}](../families/{fam[1]}.qmd) · '
        f'[{m["engine"]}]({ENGINES[m["engine"]]}) · Runs as: {m["tool"]} · '
        f'Reference implementation: {m["reference"]}.',
        "",
    ]
    if str(m["verified"]).lower() == "true":
        check = "✓ The formulation was checked against the book."
    else:
        check = "Not yet checked against the book."
    if m.get("source-note"):
        check += " " + m["source-note"]
    lines += [f"Source check: {check}", ":::", ""]
    return "\n".join(lines)


def ojs_cells(body):
    cells = re.findall(r"```\{ojs\}\n(.*?)```", body, re.S)
    out = []
    for c in cells:
        code = "\n".join(l for l in c.rstrip("\n").split("\n") if not l.startswith("//|"))
        out.append(code.strip("\n"))
    return "\n\n".join(out)


def netlogo_code(path):
    text = read(path)
    return text.split("@#$#@#$#@")[0].strip("\n")


def code_block(e):
    slug, m = e["slug"], e["meta"]
    tabs = [("Observable JS", "js", ojs_cells(e["body"]))]
    if m["engine"] == "Agent-based":
        nlogo = os.path.join(ROOT, "abm", f"{slug}.nlogo")
        exp = os.path.join(ROOT, "abm", f"{slug}.R")
        intro = ("The **NetLogo** model is the reference implementation, and the **nlrx** script runs the "
                 "experiment whose results are charted above (NetLogo 6.4, nlrx 0.4). The **Observable JS** "
                 "replays the same rules in your browser, with its own random numbers.")
        if os.path.exists(nlogo):
            tabs.append(("NetLogo", "netlogo", netlogo_code(nlogo)))
        if os.path.exists(exp):
            tabs.append(("nlrx (R)", "r", read(exp).rstrip("\n")))
    else:
        rpath = os.path.join(ROOT, "R", f"{slug}.R")
        intro = (f"The **Observable JS** runs on this page. The **R** version is the reference "
                 f"implementation ({m['reference']}): same model and defaults, with the controls as "
                 f"variables at the top.")
        if os.path.exists(rpath):
            tabs.append(("R", "r", read(rpath).rstrip("\n")))
    parts = [CODE_START, "", '<details class="code-fold model-code">', "<summary>Show model code</summary>", "",
             intro, "", '::: {.panel-tabset group="model-language"}', ""]
    for name, lang, code in tabs:
        parts += [f"## {name} {{.unlisted}}", "", f"```{{.{lang}}}", code, "```", ""]
    parts += [":::", "", "</details>", "", CODE_END, ""]
    return "\n".join(parts)


def update_entry(e):
    m, front, body = e["meta"], e["front"], e["body"]
    front = set_front_line(front, "categories", f'["{m["family"]}", "{m["engine"]}"]')
    # Callout right after the front matter.
    body = CALLOUT_RE.sub("", body, count=1).lstrip("\n")
    body = "\n" + callout(e) + "\n" + body
    # Generated code block before "## Takeaways".
    body = CODE_RE.sub("", body)
    block = code_block({**e, "body": body})
    if "\n## Takeaways" not in body:
        sys.exit(f"{e['slug']}: no '## Takeaways' section")
    body = body.replace("\n## Takeaways", "\n" + block + "\n## Takeaways", 1)
    body = re.sub(r"\n{3,}", "\n\n", body)
    return write(e["path"], f"---\n{front}\n---\n{body}")


def listing_page(path, title, description, include_key, include_value, intro, contents="../models/*.qmd"):
    text = f"""---
title: "{title}"
date: {DATE}
description: "{description}"
sidebar: false
toc: false
listing:
  id: models
  contents: "{contents}"
  type: table
  sort: "order"
  sort-ui: [order, title, chapter]
  filter-ui: true
  page-size: 100
  include:
    {include_key}: "{include_value}"
  fields: [order, title, description, chapter, engine]
  field-display-names:
    order: "#"
    title: "Model"
    description: "What it says"
    chapter: "Ch."
    engine: "Built as"
---

<!-- Generated by scripts/build_site.py. Don't edit; change FAMILIES there. -->

{intro}

::: {{#models}}
:::
"""
    return write(path, text)


def main():
    entries = load_entries()
    changed = []
    for e in entries:
        if update_entry(e):
            changed.append(e["slug"])
    entries = load_entries()

    os.makedirs(os.path.join(ROOT, "families"), exist_ok=True)
    for name, slug, icon, desc in FAMILIES:
        n = sum(1 for e in entries if e["meta"]["family"] == name)
        listing_page(os.path.join(ROOT, "families", f"{slug}.qmd"), name, desc, "family", name,
                     f"{desc} {n} model{'s' if n != 1 else ''}, in the order the book presents them.")
    n_abm = sum(1 for e in entries if e["meta"]["engine"] == "Agent-based")
    listing_page(
        os.path.join(ROOT, "agent-based.qmd"), "Agent-based models",
        "The models built in NetLogo and run as experiments with nlrx.", "engine", "Agent-based",
        f"These {n_abm} models are populations of agents following local rules, so their outcomes "
        "emerge from interaction and differ from run to run. Each one is a NetLogo 6.4 model, run "
        "across parameter values and random seeds by an [nlrx](https://docs.ropensci.org/nlrx/) "
        "experiment in R. Its page charts those results and also replays the same rules in your "
        "browser so you can watch a single run unfold. Every other model on this site is "
        "equation-based and computed live on its page.", contents="models/*.qmd")

    # Home-page family cards.
    cards = ["```{=html}", '<div class="topic-grid">']
    for name, slug, icon, desc in FAMILIES:
        n = sum(1 for e in entries if e["meta"]["family"] == name)
        cards.append(
            f'<a class="topic-card" href="families/{slug}.html"><span class="topic-name">'
            f'<i class="bi bi-{icon} topic-icon" aria-hidden="true"></i>{name}</span>'
            f'<span class="topic-count">{n} model{"s" if n != 1 else ""}</span>'
            f'<span class="topic-desc">{desc}</span></a>')
    cards += ["</div>", "```", ""]
    write(os.path.join(ROOT, "_family-cards.md"),
          "<!-- Generated by scripts/build_site.py. Don't edit. -->\n\n" + "\n".join(cards))

    # Sidebar.
    lines = ["# Generated by scripts/build_site.py. Don't edit.", "website:", "  sidebar:",
             "    - id: models", "      title: \"Models\"", "      style: docked", "      contents:"]
    for name, slug, icon, desc in FAMILIES:
        fam = [e for e in entries if e["meta"]["family"] == name]
        if not fam:
            continue
        lines += [f'        - section: "{name}"', f"          href: families/{slug}.qmd", "          contents:"]
        for e in fam:
            lines.append(f'            - text: "{e["meta"]["order"]}. {e["meta"]["title"]}"')
            lines.append(f"              href: models/{e['slug']}.qmd")
    write(os.path.join(ROOT, "_sidebar.yml"), "\n".join(lines) + "\n")

    print(f"{len(entries)} models; updated {len(changed)} entr{'y' if len(changed) == 1 else 'ies'}"
          + (f": {', '.join(changed)}" if changed and len(changed) <= 10 else ""))


if __name__ == "__main__":
    main()
