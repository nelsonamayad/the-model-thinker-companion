"""Regenerate everything derived from the model entries.

Run from the project root after adding an entry, changing its front matter,
its OJS cells, its R/ script or its abm/ files:

    python scripts/build_site.py

It writes or updates:
  - categories: [family, engine] in each entry (the clickable tags and the
    category filter on the home-page table)
  - the source callout at the top of each entry (book chapter and pages,
    family, how it is built, source check)
  - the "Show model code" block after each entry's interactive model: tabs
    with the page's Observable JS, and the R reference script (R/<slug>.R) or,
    for agent-based models, the NetLogo model (abm/<slug>.nlogo) and the nlrx
    experiment (abm/<slug>.R)
  - families/<slug>.qmd: one listing page per family
  - agent-based.qmd: listing of the agent-based models
  - _family-cards.md: family cards for the home page
  - _sidebar.yml: the docked sidebar, models grouped by family in book order

Front matter is parsed by a small reader that supports `key: value`
scalars and inline lists (`[a, "b c"]`), which is all the entries use.
"""

